// Упрощённое выделение основы слова для русского языка (без словарей).
// Используется только как опция «объединять словоформы» и может ошибаться.
const RU_ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'иях', 'иям', 'ией', 'ешь', 'ишь', 'ете', 'ите', 'ает', 'яет', 'ует',
  'ов', 'ев', 'ей', 'ой', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ам', 'ям', 'ах', 'ях', 'ом', 'ем', 'ую', 'юю', 'ть', 'ся', 'сь', 'ит', 'ат', 'ят', 'ут', 'ют',
  'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'ь', 'й',
];
const EN_ENDINGS = ['ing', 'ies', 'ied', 'es', 'ed', 's'];

export function stem(word) {
  if (word.length <= 4) return word;
  const list = /[а-я]/.test(word) ? RU_ENDINGS : EN_ENDINGS;
  for (const end of list) {
    if (word.endsWith(end) && word.length - end.length >= 3) return word.slice(0, -end.length);
  }
  return word;
}
